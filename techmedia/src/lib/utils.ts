/**
 * Turns a title (Korean or English) into a URL-safe slug.
 * Korean characters are preserved (Next.js/Vercel handle UTF-8 URLs fine),
 * we just strip characters that break URLs and collapse whitespace.
 */
export function slugify(input: string): string {
  return input
    .trim()
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s-]/gu, "")
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-")
    .slice(0, 80);
}

export function formatDate(iso: string): string {
  const d = new Date(iso);
  return d.toLocaleDateString("ko-KR", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });
}
